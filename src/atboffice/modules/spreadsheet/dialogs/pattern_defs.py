def create_pattern_pixmap(
    name: str,
    fg_color: str | QColor = "#000000",
    bg_color: str | QColor = "#FFFFFF",
    size: tuple[int, int] = (16, 16),
) -> QPixmap:
    """Create a QPixmap rendering the specified 8x8 pattern tiled to size."""
    rows = PATTERNS.get(name)
    if not rows:
        # Fallback to solid bg
        pixmap = QPixmap(size[0], size[1])
        pixmap.fill(QColor(bg_color))
        return pixmap

    fg = QColor(fg_color)
    bg = QColor(bg_color)

    # 1. Create 8x8 base tile
    tile = QImage(8, 8, QImage.Format.Format_ARGB32_Premultiplied)
    for y, row_bits in enumerate(rows):
        for x in range(8):
            is_set = (row_bits & (0x80 >> x)) != 0
            tile.setPixelColor(x, y, fg if is_set else bg)

    # 2. Tile into target size
    pixmap = QPixmap(size[0], size[1])
    painter = QPainter(pixmap)
    painter.drawTiledPixmap(0, 0, size[0], size[1], QPixmap.fromImage(tile))
    painter.end()

    return pixmap


def create_pattern_brush(
    name: str,
    fg_color: str | QColor = "#000000",
    bg_color: str | QColor = "#FFFFFF",
) -> QBrush:
    """Create a texture QBrush for painting cell backgrounds."""
    pixmap = create_pattern_pixmap(name, fg_color, bg_color, (8, 8))
    return QBrush(pixmap)
